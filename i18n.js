(function () {
  var STORAGE_KEY = 'keluaLang';

  function getLang() {
    try {
      return localStorage.getItem(STORAGE_KEY) || 'it';
    } catch (e) {
      return 'it';
    }
  }

  function setStoredLang(lang) {
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
  }

  window.keluaT = function (key) {
    var lang = getLang();
    var dict = window.KELUA_I18N[lang] || window.KELUA_I18N.it;
    if (dict[key] != null) return dict[key];
    return (window.KELUA_I18N.it[key] != null) ? window.KELUA_I18N.it[key] : key;
  };

  window.keluaLang = getLang;

  function applyTranslations(lang) {
    var dict = window.KELUA_I18N[lang] || window.KELUA_I18N.it;
    document.documentElement.lang = lang;

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (dict[key] != null) el.textContent = dict[key];
    });

    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-html');
      if (dict[key] != null) el.innerHTML = dict[key];
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-placeholder');
      if (dict[key] != null) el.setAttribute('placeholder', dict[key]);
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-aria-label');
      if (dict[key] != null) el.setAttribute('aria-label', dict[key]);
    });

    document.querySelectorAll('[data-lang-toggle]').forEach(function (btn) {
      btn.classList.toggle('is-active', btn.getAttribute('data-lang-toggle') === lang);
    });

    document.dispatchEvent(new CustomEvent('kelua:lang-changed', { detail: { lang: lang } }));
  }

  window.keluaSetLang = function (lang) {
    setStoredLang(lang);
    applyTranslations(lang);
  };

  function init() {
    applyTranslations(getLang());
    document.querySelectorAll('[data-lang-toggle]').forEach(function (btn) {
      btn.addEventListener('click', function () {
        window.keluaSetLang(btn.getAttribute('data-lang-toggle'));
      });
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
